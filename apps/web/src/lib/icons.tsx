/**
 * The shell's few icons (spec/src/design.md §Clean lines): drawn, not typed.
 * A Unicode arrow or gear is whatever the device's font makes of it — thin on
 * one machine, an emoji on the next — so chrome controls use these strokes
 * instead: one weight, round joins, `currentColor`, on a 20-unit grid.
 */
import type { ReactNode } from "react";

function Icon({ children, size = 18 }: { children: ReactNode; size?: number }) {
  return (
    <svg
      viewBox="0 0 20 20"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth="1.6"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {children}
    </svg>
  );
}

/** A window with its side panel, and an arrow tucking the panel away. */
export function PanelCloseIcon({ size }: { size?: number }) {
  return (
    <Icon {...(size ? { size } : {})}>
      <rect x="2.5" y="3.5" width="15" height="13" rx="2.5" />
      <path d="M7.5 3.5v13" />
      <path d="M13.5 8l-2 2 2 2" />
    </Icon>
  );
}

